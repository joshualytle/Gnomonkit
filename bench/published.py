"""The published round: one counts file, and the two README tables generated from it.

The project README shows bare against gnomonkit; bench/README.md shows every arm. Typed by hand,
the two drift apart: one gets the new round and the other keeps the old one. Both are generated
from bench/latest.json, between marker comments, and a test fails when either differs from what
the file produces.

latest.json holds counts only (k/n per family and arm, the date, the model, the repetitions). No
run text, cost or stderr: the same rule as the report.
"""
from __future__ import annotations

import json
import re
from datetime import date
from pathlib import Path

from bench.aggregate import family_tally
from bench.report import ARM_ORDER, FAMILY_ORDER

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
LATEST = HERE / "latest.json"
MAIN_README = ROOT / "README.md"
BENCH_README = HERE / "README.md"

# The main README shows interjection first: it is the row a reader of the project page cares
# about most. The bench README keeps the report's order.
MAIN_FAMILIES = ("interjection", "skills", "guards")
MAIN_ARMS = (("bare", "without Gnomonkit"), ("gnomonkit", "with Gnomonkit"))
BENCH_FAMILIES = ("interjection", "skills", "guards", "precedent")
NO_ARM = "no arm yet"


def summary(results: dict, when: str, mode: str = "container") -> dict:
    """The counts a published table needs, from a round's results.json."""
    records = results.get("records") or []
    ft = family_tally(records)
    reps = max((int(r.get("rep") or 0) for r in records), default=0) + 1 if records else 0
    tally: dict = {}
    for fam in FAMILY_ORDER:
        for arm in ARM_ORDER:
            cell = ft.get((fam, arm))
            if cell and cell["n"]:
                tally.setdefault(fam, {})[arm] = [cell["k"], cell["n"]]
    return {"round": when, "model": results.get("model", "?"), "reps": reps, "mode": mode, "tally": tally}


def _month(iso: str) -> str:
    d = date.fromisoformat(iso)
    return d.strftime("%B ") + str(d.year)


def _times(n: int) -> str:
    return {1: "once", 2: "twice", 3: "three times"}.get(n, f"{n} times")


def _model(s: dict) -> str:
    m = str(s.get("model") or "?")
    return m[:1].upper() + m[1:]


def _n(s: dict, fam: str) -> int:
    return max((c[1] for c in s["tally"].get(fam, {}).values()), default=0)


def _cell(s: dict, fam: str, arm: str) -> str:
    c = s["tally"].get(fam, {}).get(arm)
    return f"{c[0]}/{c[1]}" if c else NO_ARM


def main_block(s: dict) -> str:
    lines = [f"[Gnomonkit Bench](bench/README.md) runs synthetic scenarios with and without Gnomonkit installed",
             f"and scores what each run did, never what it said. One round on {_model(s)} in {_month(s['round'])}, "
             f"every", f"scenario {_times(s['reps'])}:", "",
             "| family (runs per arm) | " + " | ".join(label for _, label in MAIN_ARMS) + " |",
             "|---|" + "---|" * len(MAIN_ARMS)]
    for fam in MAIN_FAMILIES:
        if fam in s["tally"]:
            lines.append(f"| {fam} ({_n(s, fam)}) | " + " | ".join(_cell(s, fam, a) for a, _ in MAIN_ARMS) + " |")
    return "\n".join(lines)


def bench_block(s: dict) -> str:
    arms = [a for a in ARM_ORDER if any(a in row for row in s["tally"].values())]
    lines = [f"{_model(s)}, {_month(s['round'])} (round of {s['round']}), every scenario {_times(s['reps'])}, "
             f"{s['mode']} mode.", "Positive scenarios only; a run passes on what it did.", "",
             "| family (runs per arm) | " + " | ".join(arms) + " |", "|---|" + "---|" * len(arms)]
    for fam in BENCH_FAMILIES:
        if fam in s["tally"]:
            lines.append(f"| {fam} ({_n(s, fam)}) | " + " | ".join(_cell(s, fam, a) for a in arms) + " |")
    return "\n".join(lines)


def _marks(name: str) -> tuple[str, str]:
    return (f"<!-- bench:{name} start: generated by `python -m bench publish`, do not edit -->",
            f"<!-- bench:{name} end -->")


def splice(text: str, name: str, block: str) -> str:
    """Replace what sits between the named markers. Missing markers are an error, never a no-op."""
    start, end = _marks(name)
    pat = re.compile(re.escape(start) + r"\n.*?\n" + re.escape(end), re.S)
    if not pat.search(text):
        raise ValueError(f"markers for bench:{name} not found")
    return pat.sub(lambda _m: f"{start}\n{block}\n{end}", text, count=1)


def targets(s: dict) -> list[tuple[Path, str, str]]:
    return [(MAIN_README, "main", main_block(s)), (BENCH_README, "latest", bench_block(s))]


def load(path: Path | None = None) -> dict:
    return json.loads(Path(path or LATEST).read_text(encoding="utf-8"))


def stale(s: dict) -> list[Path]:
    """The README files whose generated block differs from what `s` produces."""
    out = []
    for path, name, block in targets(s):
        text = path.read_text(encoding="utf-8")
        if splice(text, name, block) != text:
            out.append(path)
    return out


def write(s: dict) -> list[Path]:
    LATEST.write_text(json.dumps(s, indent=2) + "\n", encoding="utf-8", newline="\n")
    changed = []
    for path, name, block in targets(s):
        text = path.read_text(encoding="utf-8")
        new = splice(text, name, block)
        if new != text:
            path.write_text(new, encoding="utf-8", newline="\n")
            changed.append(path)
    return changed
